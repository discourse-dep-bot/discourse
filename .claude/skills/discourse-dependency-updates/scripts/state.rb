#!/usr/bin/env ruby
# frozen_string_literal: true

# Reads and writes the dependency-updates state, which lives in `state.json` on
# its own branch with no history in common with main.
#
#   state.rb read                        Prints state.json, or an empty state if the branch does not exist.
#   state.rb write FILE [--log TEXT]     Commits FILE as state.json, appends TEXT to log/<date>.md,
#                                        regenerates README.md from the state, and pushes.
#
# `write` never forces. If another run has pushed since the last `read`, the push
# is rejected and the script exits with status 2: read again, merge your changes
# into the newer state, and write again.
#
# Environment: STATE_REMOTE (default "origin"), STATE_BRANCH (default "dep-bot"),
# STATE_REPO (default "discourse/discourse", used for links in README.md).

require "json"
require "open3"
require "tempfile"
require "time"

REMOTE = ENV.fetch("STATE_REMOTE", "origin")
BRANCH = ENV.fetch("STATE_BRANCH", "dep-bot")
TRACKING = "refs/remotes/#{REMOTE}/#{BRANCH}"
REPO = ENV.fetch("STATE_REPO", "discourse/discourse")
EMPTY_STATE = { "version" => 1, "lease" => nil, "prs" => [], "held" => [], "handed_over" => [] }

def git(*args, env: {}, input: nil, allow_failure: false)
  out, err, status = Open3.capture3(env, "git", *args, stdin_data: input)
  abort "git #{args.join(" ")} failed: #{err}" if !status.success? && !allow_failure
  status.success? ? out.strip : nil
end

def fetch_state_branch
  git("fetch", "--quiet", REMOTE, "+refs/heads/#{BRANCH}:#{TRACKING}", allow_failure: true)
  git("rev-parse", "--verify", "--quiet", TRACKING, allow_failure: true)
end

def read_state
  parent = fetch_state_branch
  return JSON.pretty_generate(EMPTY_STATE) unless parent
  git("show", "#{parent}:state.json")
end

def cell(text) = text.to_s.gsub("|", "\\|").gsub(/\s*\n\s*/, " ")

def pr_link(number) = "[##{number}](https://github.com/#{REPO}/pull/#{number})"

def update_line(update)
  "`#{update["name"]}` #{update["from"]} → #{update["to"]} (#{update["ecosystem"]})"
end

def render_readme(state, latest_log)
  prs = state["prs"] || []
  held = state["held"] || []
  handed_over = state["handed_over"] || []
  lease = state["lease"]

  out = ["# Dependency updates", ""]
  out << "Generated from `state.json` at #{Time.now.utc.strftime("%Y-%m-%d %H:%M UTC")}. " \
    "Do not edit this file. To change what the agent does, comment on one of its PRs, " \
    "or edit `state.json` on this branch. [SETUP.md](SETUP.md) explains how the bot runs."
  out << ""
  out << (
    if lease
      "A run is in progress. Its lease expires at #{lease["expires_at"]}."
    else
      "No run is in progress."
    end
  )

  out += ["", "## Open PRs", ""]
  if prs.empty?
    out << "None."
  else
    out << "| PR | Kind | Status | CI | Updates | Notes |"
    out << "| --- | --- | --- | --- | --- | --- |"
    prs.each do |pr|
      ci = pr.dig("ci", "result") || "running"
      failing = pr.dig("ci", "failing") || []
      ci += ", #{failing.size} failing" if failing.any?
      notes = []
      notes << "replaces #{pr_link(pr["replaces"])}" if pr["replaces"]
      notes << "escalated #{pr["escalated_at"]}" if pr["escalated_at"]
      set_aside = pr.dig("bisect", "set_aside") || []
      notes << "#{set_aside.size} set aside" if set_aside.any?
      out << "| #{pr_link(pr["number"])} | #{pr["kind"]} | #{pr["status"]} | #{ci} | " \
        "#{(pr["updates"] || []).size} | #{cell(notes.join(", "))} |"
    end

    prs.each do |pr|
      out += ["", "### #{pr_link(pr["number"])} #{pr["kind"]}", ""]
      (pr["updates"] || []).each { |update| out << "- #{update_line(update)}" }
      failing = pr.dig("ci", "failing") || []
      out += ["", "Failing:", *failing.map { |test| "- `#{test}`" }] if failing.any?
    end
  end

  out += ["", "## Held", ""]
  if held.empty?
    out << "None."
  else
    out << "| Package | Versions | Reason | Since | Recheck after |"
    out << "| --- | --- | --- | --- | --- |"
    held.each do |hold|
      out << "| `#{hold["name"]}` (#{hold["ecosystem"]}) | #{cell(hold["versions"])} | " \
        "#{cell(hold["reason"])} | #{hold["since"]} | #{hold["recheck_after"]} |"
    end
  end

  if handed_over.any?
    out += ["", "## Handed over", ""]
    handed_over.each do |pr|
      out << "- #{pr_link(pr["number"])}: #{(pr["updates"] || []).map { |u| "`#{u["name"]}`" }.join(", ")}"
    end
  end

  out += ["", "## Latest activity", "", latest_log.strip.sub(/\A## /, "### ")] if latest_log

  out << ""
  out.join("\n")
end

def write_state(file, log)
  state = JSON.parse(File.read(file)) # refuse to save invalid JSON
  parent = git("rev-parse", "--verify", "--quiet", TRACKING, allow_failure: true)

  Tempfile.create("state-index") do |index|
    env = { "GIT_INDEX_FILE" => index.path }
    parent ? git("read-tree", parent, env:) : git("read-tree", "--empty", env:)

    blob = git("hash-object", "-w", file)
    git("update-index", "--add", "--cacheinfo", "100644,#{blob},state.json", env:)

    if log
      path = "log/#{Time.now.utc.strftime("%Y-%m-%d")}.md"
      existing = parent && git("show", "#{parent}:#{path}", allow_failure: true)
      entry = "## #{Time.now.utc.iso8601}\n\n#{log.strip}\n"
      content = [existing, entry].compact.join("\n")
      log_blob = git("hash-object", "-w", "--stdin", input: content)
      git("update-index", "--add", "--cacheinfo", "100644,#{log_blob},#{path}", env:)
    end

    newest_log = git("ls-files", "log/", env:).split("\n").max
    latest_log = newest_log && git("show", ":#{newest_log}", env:).split(/^(?=## )/).last
    readme = render_readme(state, latest_log)
    readme_blob = git("hash-object", "-w", "--stdin", input: readme)
    git("update-index", "--add", "--cacheinfo", "100644,#{readme_blob},README.md", env:)

    tree = git("write-tree", env:)
    parent_args = parent ? ["-p", parent] : []
    commit = git("commit-tree", tree, *parent_args, "-m", "Update dependency state")

    _, err, status =
      Open3.capture3("git", "push", "--quiet", REMOTE, "#{commit}:refs/heads/#{BRANCH}")
    unless status.success?
      warn "State changed since it was read; read it again and reapply your changes.\n#{err}"
      exit 2
    end
    git("update-ref", TRACKING, commit)
  end
end

case ARGV.shift
when "read"
  puts read_state
when "write"
  file = ARGV.shift or abort "Usage: state.rb write FILE [--log TEXT]"
  log = (i = ARGV.index("--log")) ? ARGV[i + 1] : nil
  write_state(file, log)
else
  abort "Usage: state.rb read | state.rb write FILE [--log TEXT]"
end
